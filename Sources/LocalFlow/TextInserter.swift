import AppKit
import ApplicationServices

/// Where the keyboard focus was when a recording started: the app, its focused window and the
/// focused text element. Compared again right before pasting.
struct FocusSnapshot {
    let pid: pid_t
    let window: AXUIElement?
    let element: AXUIElement?

    static func capture() -> FocusSnapshot {
        let pid = NSWorkspace.shared.frontmostApplication?.processIdentifier ?? 0
        let system = AXUIElementCreateSystemWide()
        var focusedRef: CFTypeRef?
        var element: AXUIElement? = nil
        var window: AXUIElement? = nil
        if AXUIElementCopyAttributeValue(system, kAXFocusedUIElementAttribute as CFString, &focusedRef) == .success,
           let ref = focusedRef {
            element = (ref as! AXUIElement)
            var windowRef: CFTypeRef?
            if AXUIElementCopyAttributeValue(element!, kAXWindowAttribute as CFString, &windowRef) == .success,
               let w = windowRef {
                window = (w as! AXUIElement)
            }
        }
        return FocusSnapshot(pid: pid, window: window, element: element)
    }

    /// True when the focused field is a password field (macOS and browsers report these as secure text fields).
    var isSecureField: Bool {
        guard let element = element else { return false }
        var ref: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, kAXSubroleAttribute as CFString, &ref) == .success else { return false }
        return (ref as? String) == (kAXSecureTextFieldSubrole as String)
    }

    /// True when it is safe to paste: same app, and, where macOS tells us, the same window and field.
    /// If the app cannot report its focus, the app check alone decides (as before).
    func stillCurrent(_ now: FocusSnapshot) -> Bool {
        guard pid == now.pid else { return false }
        if let a = window, let b = now.window, !CFEqual(a, b) { return false }
        if let a = element, let b = now.element, !CFEqual(a, b) { return false }
        return true
    }
}

/// Puts text into whatever app has keyboard focus: pasteboard + synthetic ⌘V,
/// then restores the previous pasteboard contents.
enum TextInserter {
    typealias Snapshot = [[NSPasteboard.PasteboardType: Data]]

    // nspasteboard.org markers: clipboard managers (Raycast, Maccy, Paste, Alfred) skip such entries.
    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    /// Long enough for slow apps (Office, Electron, remote desktops) to read the pasteboard before it is restored.
    private static let restoreDelay: TimeInterval = 1.5
    /// The user's clipboard from before a paste whose restore is still pending, and the change count we left.
    private static var pendingOriginal: Snapshot?
    private static var pendingChange = -1

    static func insert(_ text: String, smartSpacing: Bool) {
        var payload = text
        if smartSpacing, needsLeadingSpace() { payload = " " + payload }

        let pb = NSPasteboard.general
        // A second dictation before the first restore: the pasteboard still holds our own text,
        // so keep the user's original contents from the first snapshot.
        let saved: Snapshot
        if let original = pendingOriginal, pb.changeCount == pendingChange { saved = original } else { saved = snapshot(pb) }
        writePrivate(payload, to: pb, extraTypes: [transientType, autoGeneratedType])
        let ourChange = pb.changeCount
        pendingOriginal = saved
        pendingChange = ourChange

        postCommandV()

        DispatchQueue.main.asyncAfter(deadline: .now() + restoreDelay) {
            guard pendingChange == ourChange else { return } // a newer dictation owns the restore
            pendingOriginal = nil
            pendingChange = -1
            // Only restore if nobody else has written to the pasteboard meanwhile.
            if pb.changeCount == ourChange { restore(pb, saved) }
        }
    }

    /// Leaves the text on the clipboard without pasting (used when the user switched apps mid-dictation,
    /// and for copying from history).
    static func copyOnly(_ text: String) {
        pendingOriginal = nil
        pendingChange = -1
        writePrivate(text, to: NSPasteboard.general, extraTypes: [])
    }

    /// Dictated text stays on this Mac (no Universal Clipboard to iPhone/iPad) and is marked
    /// concealed so clipboard managers don't keep a copy.
    private static func writePrivate(_ text: String, to pb: NSPasteboard, extraTypes: [NSPasteboard.PasteboardType]) {
        pb.prepareForNewContents(with: .currentHostOnly)
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        for type in [concealedType] + extraTypes { item.setData(Data(), forType: type) }
        pb.writeObjects([item])
    }

    private static func postCommandV() {
        let src = CGEventSource(stateID: .combinedSessionState)
        guard let down = CGEvent(keyboardEventSource: src, virtualKey: 9, keyDown: true),
              let up = CGEvent(keyboardEventSource: src, virtualKey: 9, keyDown: false) else { return }
        down.flags = .maskCommand
        up.flags = .maskCommand
        down.post(tap: .cghidEventTap)
        up.post(tap: .cghidEventTap)
    }

    private static func snapshot(_ pb: NSPasteboard) -> Snapshot {
        (pb.pasteboardItems ?? []).map { item in
            var dict: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) { dict[type] = data }
            }
            return dict
        }
    }

    private static func restore(_ pb: NSPasteboard, _ snap: Snapshot) {
        pb.clearContents()
        // A password copied from a password manager is marked concealed/transient and meant to be
        // cleared soon; putting it back would restart its life on the clipboard, so leave it cleared.
        if snap.contains(where: { $0[concealedType] != nil || $0[transientType] != nil }) { return }
        let items: [NSPasteboardItem] = snap.compactMap { dict in
            guard !dict.isEmpty else { return nil }
            let item = NSPasteboardItem()
            for (type, data) in dict { item.setData(data, forType: type) }
            return item
        }
        if !items.isEmpty { pb.writeObjects(items) }
    }

    /// Looks at the character before the caret in the focused text field (via Accessibility).
    private static func needsLeadingSpace() -> Bool {
        let system = AXUIElementCreateSystemWide()
        var focusedRef: CFTypeRef?
        guard AXUIElementCopyAttributeValue(system, kAXFocusedUIElementAttribute as CFString, &focusedRef) == .success,
              let focusedRef = focusedRef else { return false }
        let element = focusedRef as! AXUIElement

        var rangeRef: CFTypeRef?
        var valueRef: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, kAXSelectedTextRangeAttribute as CFString, &rangeRef) == .success,
              AXUIElementCopyAttributeValue(element, kAXValueAttribute as CFString, &valueRef) == .success,
              let rangeRef = rangeRef, let value = valueRef as? String else { return false }

        var range = CFRange()
        guard AXValueGetValue(rangeRef as! AXValue, .cfRange, &range) else { return false }
        let utf16 = Array(value.utf16)
        guard range.location > 0, range.location <= utf16.count else { return false }
        let prev = utf16[range.location - 1]
        guard let scalar = Unicode.Scalar(prev) else { return false }
        let ch = Character(scalar)
        if ch.isWhitespace || ch.isNewline { return false }
        if "([{\"'“‘/-—".contains(ch) { return false }
        return true
    }
}
